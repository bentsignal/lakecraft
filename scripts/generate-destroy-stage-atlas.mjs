import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { decodePng } from "./png-rgba.mjs";
import { encodeStaticBytes } from "./static-byte-encoding.mjs";

const [manifestArgument, outputArgument] = process.argv.slice(2);
if (!manifestArgument || !outputArgument) {
  throw new Error("Usage: node scripts/generate-destroy-stage-atlas.mjs manifest.json output.ts");
}

const manifestPath = resolve(manifestArgument);
const outputPath = resolve(outputArgument);
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const width = 16;
const height = 16 * 10;
const rgba = new Uint8Array(width * height * 4);
const sourceSha256 = {};

for (let stage = 0; stage < 10; stage += 1) {
  const name = `destroy_stage_${stage}`;
  const payload = manifest.blocks?.[name];
  if (typeof payload !== "string" || !payload) throw new Error(`Missing imported ${name}.`);
  const png = Buffer.from(payload, "base64");
  const decoded = decodePng(png);
  if (decoded.width !== width || decoded.height !== 16) {
    throw new Error(`${name} must be an exact 16x16 texture.`);
  }
  rgba.set(decoded.rgba, stage * width * 16 * 4);
  sourceSha256[name] = createHash("sha256").update(png).digest("hex");
}

// The tiny destroy atlas still benefits substantially from the same bounded
// LZ token format as the world atlas. This is generation-only tooling; runtime
// expands one immutable 10 KiB texture with the shared decoder.
function packStaticBytes(bytes) {
  const packed = [];
  let index = 0;
  while (index < bytes.length) {
    const control = packed.length;
    packed.push(0);
    let flags = 0;
    for (let bit = 0; bit < 8 && index < bytes.length; bit += 1) {
      let length = 0;
      let distance = 0;
      for (let source = Math.max(0, index - 4_095); source < index; source += 1) {
        let candidate = 0;
        while (candidate < 273 && index + candidate < bytes.length
          && bytes[source + candidate] === bytes[index + candidate]) candidate += 1;
        if (candidate > length) {
          length = candidate;
          distance = index - source;
        }
      }
      if (length >= 3) {
        if (length === 18) length = 17;
        flags |= 1 << bit;
        const value = (Math.min(length, 18) - 3) * 4_096 + distance;
        packed.push(value >> 8, value & 255);
        if (length > 17) packed.push(length - 18);
        index += length;
      } else packed.push(bytes[index++]);
    }
    packed[control] = flags;
  }
  return new Uint8Array(packed);
}

const packed = packStaticBytes(rgba);
const source = `// Generated by scripts/generate-destroy-stage-atlas.mjs from the hash-pinned Minecraft 26.2 import.\n`
  + `import { decodeStaticBytes } from "../../staticData.ts";\n`
  + `export const DESTROY_STAGE_COUNT=10;\n`
  + `export const DESTROY_STAGE_WIDTH=${width};\n`
  + `export const DESTROY_STAGE_HEIGHT=16;\n`
  + `export const DESTROY_STAGE_RGBA=decodeStaticBytes(${JSON.stringify(encodeStaticBytes(packed))},${rgba.length},${packed.length},true);\n`
  + `export const DESTROY_STAGE_RGBA_SHA256=${JSON.stringify(createHash("sha256").update(rgba).digest("hex"))};\n`
  + `export const DESTROY_STAGE_SOURCE_SHA256=${JSON.stringify(sourceSha256)} as const;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source);
console.log(JSON.stringify({ outputPath, rgbaBytes: rgba.length, packedBytes: packed.length,
  rgbaSha256: createHash("sha256").update(rgba).digest("hex"), sourceSha256 }));
