import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

const [assetsArgument, outputArgument = "client/game/generated/officialSoundAssets.ts", manifestArgument = "scripts/generated/minecraft-sound-assets-v26.2.json"] = process.argv.slice(2);
if (!assetsArgument) throw new Error("Usage: node scripts/import-minecraft-sound-assets.mjs <minecraft-assets-dir> [typescript-output] [manifest-output]");

const VERSION = "26.2";
const INDEX_ID = "32";
const INDEX_SHA1 = "4050401d6e5df16ef17c2d0adea6fd37937badae";
const assetsRoot = resolve(assetsArgument);
const indexPath = join(assetsRoot, "indexes", `${INDEX_ID}.json`);
const indexBytes = await readFile(indexPath);
const index = JSON.parse(indexBytes.toString("utf8"));
const sha1 = (bytes) => createHash("sha1").update(bytes).digest("hex");
if (sha1(indexBytes) !== INDEX_SHA1) throw new Error(`Minecraft asset index ${INDEX_ID} hash mismatch.`);

const soundsEntry = index.objects?.["minecraft/sounds.json"];
if (!soundsEntry?.hash) throw new Error("Minecraft sounds.json is missing from the asset index.");
const soundsBytes = await readFile(join(assetsRoot, "objects", soundsEntry.hash.slice(0, 2), soundsEntry.hash));
if (sha1(soundsBytes) !== soundsEntry.hash) throw new Error("Minecraft sounds.json object hash mismatch.");
const sounds = JSON.parse(soundsBytes.toString("utf8"));

const surfaces = ["grass", "stone", "wood", "sand", "gravel", "metal", "glass"];
const mobs = ["pig", "cow", "sheep", "chicken", "zombie", "skeleton", "creeper", "spider"];
const requested = [];
for (const surface of surfaces) for (const [cue, action] of [["footstep", "step"], ["blockBreak", "break"], ["blockPlace", "place"]]) {
  requested.push([`${cue}:${surface}`, `block.${surface}.${action}`]);
}
for (const mob of mobs) for (const [cue, action] of [["mobIdle", "ambient"], ["mobHurt", "hurt"], ["mobDeath", "death"]]) {
  const event = `entity.${mob}.${action}`;
  if (sounds[event]) requested.push([`${cue}:${mob}`, event]);
}

const groups = {};
const manifestGroups = {};
for (const [key, event] of requested) {
  const names = (sounds[event]?.sounds ?? []).map((entry) => typeof entry === "string" ? entry : entry.name);
  if (names.length === 0) throw new Error(`Minecraft sound event ${event} has no concrete sounds.`);
  const resolved = names.slice(0, 1).map((name) => {
    const path = `minecraft/sounds/${name}.ogg`;
    const object = index.objects?.[path];
    if (!object?.hash || !Number.isSafeInteger(object.size)) throw new Error(`Missing indexed sound ${path}.`);
    return { path, hash: object.hash, size: object.size };
  });
  groups[key] = resolved.map(({ hash, size }) => [hash, size]);
  manifestGroups[key] = { event, assets: resolved };
}

const provenance = {
  format: "lakecraft.minecraft-sound-assets.v1",
  minecraftVersion: VERSION,
  assetIndexId: INDEX_ID,
  assetIndexSha1: INDEX_SHA1,
  soundsJsonSha1: soundsEntry.hash,
  resourceBaseUrl: "https://resources.download.minecraft.net",
};
const keys = Object.keys(groups);
const uniqueHashes = [...new Set(keys.map((key) => groups[key][0][0]))];
const hashIndexes = keys.map((key) => uniqueHashes.indexOf(groups[key][0][0]).toString(36)).join("");
const source = `/* Generated by scripts/import-minecraft-sound-assets.mjs. Do not edit. */\n`
  + `export const OFFICIAL_SOUND_BASE = ${JSON.stringify(provenance.resourceBaseUrl)};\n`
  + `export const OFFICIAL_SOUND_HASH_BYTES = ${JSON.stringify(Buffer.concat(uniqueHashes.map((hash) => Buffer.from(hash, "hex"))).toString("base64"))};\n`
  + `export const OFFICIAL_SOUND_INDEXES = ${JSON.stringify(hashIndexes)};\n`;
const manifest = { ...provenance, sourceIndexBytes: indexBytes.length, groups: manifestGroups };

for (const [path, contents] of [[resolve(outputArgument), source], [resolve(manifestArgument), `${JSON.stringify(manifest, null, 2)}\n`]]) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}
console.log(`Imported ${Object.keys(groups).length} Minecraft ${VERSION} sound groups.`);
